#!/usr/bin/env python3
"""Generate both implementations of the builtin metadata table.

`Bootstrap/builtin_spec.py` is the single source.  Stage 0 imports the generated
Python table; the self-hosted compiler imports the generated tlang name -> ID
mapping.  Keeping the IDs here prevents stage 0 and stage 1 from drifting into
different dispatch behaviour.

    python3 Tools/gen_builtins.py           # rewrite both generated files
    python3 Tools/gen_builtins.py --check   # fail if either file is stale
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from Bootstrap.builtin_spec import (  # noqa: E402
    BUILTIN_SPECS, HOSTED_ONLY, KERNEL_ONLY,
)

PY_OUT = os.path.join(ROOT, "Bootstrap", "builtins_gen.py")
TL_OUT = os.path.join(ROOT, "Runtime", "builtins_gen.tl")


def _mode(name):
    """Which build mode a builtin needs; "any" is the default."""
    if name in KERNEL_ONLY:
        return "kernel"
    if name in HOSTED_ONLY:
        return "hosted"
    return "any"


def _args_repr(args):
    if args is None:
        return None
    return "(" + "".join(
        "(" + ", ".join(repr(kind) for kind in allowed) + ",),"
        for allowed in args) + ")"


def render_py():
    lines = [
        '"""Generated by Tools/gen_builtins.py; edit Bootstrap/builtin_spec.py."""',
        "",
        "BUILTIN_IDS = {",
    ]
    for name, ident, _arity, _result, _symbol, _args, _stage0 in BUILTIN_SPECS:
        lines.append(f"    {name!r}: {ident},")
    lines.extend(["}", "", "BUILTIN_NAMES = {"])
    for name, ident, _arity, _result, _symbol, _args, _stage0 in BUILTIN_SPECS:
        lines.append(f"    {ident}: {name!r},")
    lines.extend(["}", "", "BUILTIN_ARGS = {"])
    for name, _ident, _arity, _result, _symbol, args, _stage0 in BUILTIN_SPECS:
        if args is not None:
            lines.append(f"    {name!r}: {_args_repr(args)},")
    lines.extend(["}", "", "BUILTINS = {"])
    for name, _ident, arity, result, symbol, _args, stage0 in BUILTIN_SPECS:
        if stage0:
            lines.append(f"    {name!r}: ({arity}, {result!r}, {symbol!r}),")
    lines.extend(["}", "", "BUILTIN_MODES = {"])
    for name, *_rest in BUILTIN_SPECS:
        mode = _mode(name)
        if mode != "any":
            lines.append(f"    {name!r}: {mode!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_tl():
    lines = [
        "# Generated by Tools/gen_builtins.py; edit Bootstrap/builtin_spec.py.",
        "",
        "fn builtin_kind(n: str) -> int {",
    ]
    for name, ident, _arity, _result, _symbol, _args, _stage0 in BUILTIN_SPECS:
        lines.append(f'  if str_eq(n, "{name}") == 1 {{')
        lines.append(f"    return {ident}")
        lines.append("  }")
    lines.extend(["  return 0", "}", ""])
    for predicate, group in (("hosted", HOSTED_ONLY), ("kernel", KERNEL_ONLY)):
        lines.append(f"fn builtin_{predicate}(n: str) -> int {{")
        for name, *_rest in BUILTIN_SPECS:
            if name in group:
                lines.append(f'  if str_eq(n, "{name}") == 1 {{')
                lines.append("    return 1")
                lines.append("  }")
        lines.extend(["  return 0", "}", ""])
    lines.append("# Argument count of a machine builtin; 0 for anything else.")
    lines.append("fn builtin_arity(n: str) -> int {")
    for name, _ident, arity, _result, _symbol, _args, _stage0 in BUILTIN_SPECS:
        if name in KERNEL_ONLY:
            lines.append(f'  if str_eq(n, "{name}") == 1 {{')
            lines.append(f"    return {arity}")
            lines.append("  }")
    lines.extend(["  return 0", "}", ""])
    lines.append("# Declared kind of argument i of a machine builtin, \"\" past the end.")
    lines.append("fn builtin_arg(n: str, i: int) -> str {")
    for name, _ident, _arity, _result, _symbol, args, _stage0 in BUILTIN_SPECS:
        if name not in KERNEL_ONLY or not args:
            continue
        lines.append(f'  if str_eq(n, "{name}") == 1 {{')
        for index, allowed in enumerate(args):
            lines.append(f'    if i == {index} {{ return "{allowed[0]}" }}')
        lines.append('    return ""')
        lines.append("  }")
    lines.extend(['  return ""', "}", ""])
    return "\n".join(lines)


def main(argv):
    py_text, tl_text = render_py(), render_tl()
    pairs = ((PY_OUT, py_text), (TL_OUT, tl_text))
    if "--check" in argv:
        for path, text in pairs:
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    current = fh.read()
            except OSError:
                print(f"{path} is missing; run Tools/gen_builtins.py",
                      file=sys.stderr)
                return 1
            if current != text:
                print(f"{path} is out of date; run Tools/gen_builtins.py",
                      file=sys.stderr)
                return 1
        print("generated builtin metadata is up to date")
        return 0
    for path, text in pairs:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
