#!/usr/bin/env python3
"""Generate both implementations of the kind-compatibility rule.

`compatible()` decides whether a value of one kind may be used where another
is wanted.  Stage 0 (Python) and the self-hosted compiler (tlang) must agree
exactly, so neither copy is maintained by hand:

    Bootstrap/kindrules_gen.py   imported by Bootstrap/lower.py
    Runtime/kinds_gen.tl         imported by tcomp.tl

    python3 Tools/gen_kinds.py           # rewrite both files
    python3 Tools/gen_kinds.py --check   # fail if either is out of date
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY_OUT = os.path.join(ROOT, "Bootstrap", "kindrules_gen.py")
TL_OUT = os.path.join(ROOT, "Runtime", "kinds_gen.tl")

HEADER_PY = '''"""Generated by Tools/gen_kinds.py; edit the generator, not this file."""

UNKNOWN = "unknown"


def is_array(kind):
    return kind in ("arr", "ptr") or kind.startswith("arr_of:")


def compatible(expected, actual):
    """Can `actual` be used where `expected` is wanted?"""
'''

PY_BODY = '''    if expected in ("", UNKNOWN) or actual in ("", UNKNOWN):
        return True
    if expected == actual:
        return True
    if expected == "float" or actual == "float":
        return False
    if actual == "int" and expected not in ("int", "str"):
        return True
    if is_array(expected) and is_array(actual):
        if expected.startswith("arr_of:") and actual.startswith("arr_of:"):
            return expected[len("arr_of:"):] == actual[len("arr_of:"):]
        return True
    return False
'''

HEADER_TL = """# Generated by Tools/gen_kinds.py; edit the generator, not this file.

fn kr_is_array(t: str) -> int {
  if str_eq(t, "arr") == 1 || str_eq(t, "ptr") == 1 || has_arr_prefix(t) == 1 {
    return 1
  }
  return 0
}

fn types_ok(want: str, got: str) -> int {
"""

TL_BODY = """  if want == "" || got == "" || str_eq(want, "unknown") == 1 || str_eq(got, "unknown") == 1 {
    return 1
  }
  if str_eq(want, got) == 1 {
    return 1
  }
  if str_eq(want, "float") == 1 || str_eq(got, "float") == 1 {
    return 0
  }
  if str_eq(got, "int") == 1 && str_eq(want, "int") == 0 && str_eq(want, "str") == 0 {
    return 1
  }
  if kr_is_array(want) == 1 && kr_is_array(got) == 1 {
    if has_arr_prefix(want) == 1 && has_arr_prefix(got) == 1 {
      if str_eq(elem_of(want), elem_of(got)) == 1 {
        return 1
      }
      return 0
    }
    return 1
  }
  return 0
}
"""


def render():
    return HEADER_PY + PY_BODY, HEADER_TL + TL_BODY


def main(argv):
    py_text, tl_text = render()
    pairs = ((PY_OUT, py_text), (TL_OUT, tl_text))
    if "--check" in argv:
        for path, text in pairs:
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    current = fh.read()
            except OSError:
                print(f"{path} is missing; run Tools/gen_kinds.py",
                      file=sys.stderr)
                return 1
            if current != text:
                print(f"{path} is out of date; run Tools/gen_kinds.py",
                      file=sys.stderr)
                return 1
        print("generated kind rules are up to date")
        return 0
    for path, text in pairs:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
