#!/usr/bin/env python3
"""Generate Runtime/runtime_gen.tl from Bootstrap/runtime.py.

The Python runtime table is the single definition of the assembly.  The
self-hosted compiler imports the generated tlang module instead of keeping a
second, hand-maintained copy.

    python3 Tools/gen_runtime.py           # rewrite the generated module
    python3 Tools/gen_runtime.py --check   # fail if it is out of date
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from Bootstrap.runtime import RUNTIME  # noqa: E402

OUT = os.path.join(ROOT, "Runtime", "runtime_gen.tl")


def _quote(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    lines = [
        "# Generated by Tools/gen_runtime.py from Bootstrap/runtime.py.",
        "# Edit the Python table, then rerun the generator; do not edit this file.",
        "",
    ]
    for name, (body, _deps) in RUNTIME.items():
        lines.append(f"fn rt_emit_{name}() {{")
        for line in body.splitlines():
            lines.append(f"  el({_quote(line)})")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(OUT, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            print(f"{OUT} is missing; run Tools/gen_runtime.py", file=sys.stderr)
            return 1
        if current != text:
            print(f"{OUT} is out of date; run Tools/gen_runtime.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
