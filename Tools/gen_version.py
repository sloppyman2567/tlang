#!/usr/bin/env python3
"""Generate the self-hosted compiler's version constant from VERSION.

VERSION is the one place a release bump edits. Stage 0 reads it directly in
Bootstrap/__init__.py; the self-hosted compiler imports the tlang constant
generated here, so neither compiler keeps a hand-maintained copy.

    python3 Tools/gen_version.py           # rewrite Runtime/version_gen.tl
    python3 Tools/gen_version.py --check   # fail if it is out of date
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_FILE = os.path.join(ROOT, "VERSION")
OUT = os.path.join(ROOT, "Runtime", "version_gen.tl")

HEADER = "# Generated by Tools/gen_version.py; edit VERSION, not this file.\n"


def version():
    with open(VERSION_FILE, "r", encoding="utf-8") as fh:
        value = fh.read().strip()
    if re.fullmatch(r"\d+\.\d+\.\d+", value) is None:
        raise SystemExit(f"VERSION is {value!r}, expected MAJOR.MINOR.PATCH")
    return value


def render():
    return HEADER + f'\nlet TLANG_VERSION = "{version()}"\n'


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(OUT, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            print(f"{OUT} is missing; run Tools/gen_version.py",
                  file=sys.stderr)
            return 1
        if current != text:
            print(f"{OUT} is out of date; run Tools/gen_version.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"{OUT} written ({version()})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
