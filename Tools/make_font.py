#!/usr/bin/env python3
"""Turn a Linux console font (PSF) into Kernel/font8.s.

The kernel console draws text from an 8x8 bitmap font, so the glyphs have to be
part of the image.  This script reads printable ASCII 32..126 out of a PSF1 or
PSF2 console font and writes them as assembly bytes.

    python3 Tools/make_font.py [font.psf[.gz]]   # default alt-8x8

Kernel/font8.s is committed, so building the kernel never needs a system font.
"""

import gzip
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Kernel", "font8.s")
DEFAULT_FONT = "/usr/share/kbd/consolefonts/alt-8x8.gz"
FIRST, LAST = 32, 126


def load(path):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as fh:
        data = fh.read()
    if data[:2] == b"\x36\x04":                       # PSF1
        mode = data[2]
        height = data[3]
        count = 512 if mode & 0x01 else 256
        offset = 4
        if mode & 0x02:                              # unicode table follows
            offset += count * (2 if mode & 0x04 else 1)
    elif data[:4] == b"\x72\xb5\x4a\x86":             # PSF2
        count, _has_unicode, height = int.from_bytes(
            data[8:12], "little"), data[12], int.from_bytes(
            data[14:16], "little")
        offset = int.from_bytes(data[16:20], "little")
        depth = int.from_bytes(data[20:24], "little")
        if depth != 8:
            raise SystemExit(f"{path}: {depth}-bit glyphs, want 8")
    elif len(data) == 256 * 8:                       # raw 8x8, no header
        return [data[i * 8:(i + 1) * 8] for i in range(256)]
    else:
        raise SystemExit(f"{path}: not a PSF1, PSF2 or raw 8x8 font")
    if height != 8:
        raise SystemExit(f"{path}: glyphs are 8x{height}, want 8x8")
    stride = 8
    glyphs = [data[offset + i * stride:offset + (i + 1) * stride]
              for i in range(count)]
    if len(glyphs) < LAST + 1:
        raise SystemExit(f"{path}: only {len(glyphs)} glyphs")
    return glyphs


def main(argv):
    path = argv[1] if len(argv) > 1 else DEFAULT_FONT
    glyphs = load(path)
    lines = [
        "# Generated by Tools/make_font.py from "
        f"{os.path.basename(path)}; do not edit.",
        "# 8x8 glyphs for ASCII 32..126, one byte per scanline, high bit left.",
        ".section .data",
        ".globl __k_font",
        ".align 8",
        "__k_font:",
    ]
    for code in range(FIRST, LAST + 1):
        row = glyphs[code]
        lines.append("  .byte " + ", ".join(f"0x{b:02x}" for b in row)
                     + f"   # {chr(code)!r}")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {LAST - FIRST + 1} glyphs")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
